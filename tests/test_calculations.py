@pytest.mark.parametrize(
    ("line", "expected"),
    [
        ("Помилка: 120 × 3 = 400 $", ["120 × 3 = 400 → правильно: 360"]),
        # ланцюжок: перевіряється кожен крок від того, що написав студент
        ("А = 70*30000=2250000/8=240000", [
            "70 × 30 000 = 2 250 000 → правильно: 2 100 000",
            "2 250 000 ÷ 8 = 240 000 → правильно: 281 250",
        ]),
        ("А = 70*30000=2100000/8=240000", ["2 100 000 ÷ 8 = 240 000 → правильно: 262 500"]),
        ("ROI = (8 000 − 500) ÷ 500 × 100% = 150%", ["(8 000 − 500) ÷ 500 × 100% = 150% → правильно: 1 500%"]),
        ("Конверсія 30 / 120 = 30%", ["30 ÷ 120 = 30% → правильно: 25%"]),
        ("ROI = (−208,29 ÷ 1 120,29) × 100% = −10%", ["(−208,29 ÷ 1 120,29) × 100% = −10% → правильно: −18,59%"]),
        ("ВП (старий) = ОП (старий) * Маржа (стара)____18’292$=64’871$*29,2%",
         ["64 871 × 29,2% = 18 292 → правильно: 18 942,33"]),
    ],
)
def test_wrong_calculations(line, expected):
    # Знаки — × і ÷ (не * і /: Telegram-розмітка їх «з'їдає»), числа — з пробілами між тисячами
    assert find_calculation_errors(line) == expected


def test_point_a_parts_must_sum_to_total():
    lines = ["А= 693*3,90 = 2700$", "А1 = 20*104$=2080$", "А2 = 673*1,1 = 730$", "Розклад за товарами:",
             "А1 = 149*4,8= 715$", "А2 = 142*12=1704$", "A3 = 12*46 = 552$", "А4 = 10*120=1200$"]
    mismatches = find_point_a_parts_mismatches(lines)
    # 2 080 + 730 = 2 810 — у межах 5% від 2 700; 715 + 1 704 + 552 + 1 200 = 4 171 — ні
    assert mismatches == ["А1 + А2 + А3 + А4 = 715 + 1 704 + 552 + 1 200 = 4 171, а точка А = 2 700"]


def test_point_a_parts_with_negative_part():
    lines = ["Точка А (серпень) – 26 600$", "Точка А 1 (гурт) – 28 200$", "Точка А 2 (роздріб) - -1 600$"]
    assert find_point_a_parts_mismatches(lines) == []


def test_point_a_parts_dash_separators_are_not_minus():
    lines = [
        "Точка А = близько 9 000,00 ($)  :",
        "А1- монтаж силового електрообладнання та мереж- (3-и клієнта) -  2 000,00 ($)",
        "А2-електрозабезпечення виробничого обладнання–(2-а клієнта)-  4 000,00 ($)",
        "А3-монтаж систем блискавкозахисту- (2-а клієнта) 1 000,00 ($)",
        "А4-електрозабезпечення освітлення- (3-и клієнта) – 1 000,00 ($)",
        "А5-електрозабезпечення електрообігріву (1-клієнт) -1 000,00 ($)",
    ]
    assert find_point_a_parts_mismatches(lines) == []


def test_pipeline_reports_calculation_errors(run_check):
    result = run_check(DocSpec(header_parts(), plain("Точка А = 120 × 30 $ = 4 000 $")))
    assert "wrong_calculation" in codes(result)
    ok = run_check(DocSpec(header_parts(), plain("Точка А = 120 × 30 $ = 3 600 $")))
    assert "wrong_calculation" not in codes(ok)
